# 输入的十六进制数据
hex_data = "0x6d, 0x6f, 0x65, 0x63, 0x74, 0x66, 0x7b, 0x54, 0x68, 0x33, 0x5f, 0x54, 0x45, 0x41, 0x5f, 0x21, 0x53, 0x5f, 0x73, 0x30, 0x5f, 0x74, 0x34, 0x73, 0x37, 0x79, 0x7e, 0x7e, 0x21, 0x21, 0x21, 0x7d"

# 1. 将字符串按逗号分隔成列表
hex_list = hex_data.split(', ')

# 2. 将每个十六进制字符串转换为整数，再转换为字符，最后拼接起来
decoded_text = "".join([chr(int(h, 16)) for h in hex_list])

print(decoded_text)
