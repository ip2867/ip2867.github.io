# 逆 S-Box
InvSbox = [0] * 256
for i in range(256): InvSbox[Sbox[i]] = i

def inv_sub_bytes(block):
    return [InvSbox[x] for x in block]

def inv_shift_rows(block):
    s = list(block)
    r0 = s[0:4]
    r1 = [s[7], s[4], s[5], s[6]]
    r2 = [s[10], s[11], s[8], s[9]]
    r3 = [s[13], s[14], s[15], s[12]]
    return r0 + r1 + r2 + r3

def inv_transform(block):
    tmp = inv_sub_bytes(block)
    res = [0]*16
    for row in range(4):
        for col in range(4):
            res[row * 4 + col] = tmp[col * 4 + row]
    return res

